export type IconName = keyof typeof icons;

/** Line icon sized to the surrounding font-size (1em) and coloured with currentColor. */
export default function Icon({
  name,
  className = "",
  strokeWidth = 1.75,
}: {
  name: IconName;
  className?: string;
  strokeWidth?: number;
}) {
  const C = icons[name];
  return <C aria-hidden="true" className={`hana-icon ${className}`} width="1em" height="1em" strokeWidth={strokeWidth} />;
}
